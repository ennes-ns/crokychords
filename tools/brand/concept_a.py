"""Banner concept A: the flat vector Croky (from trace_mark.py) next to a one-colour grotesk wordmark.

usage: concept_a.py MARK_FRAGMENT FONT OUT_SVG
The wordmark is converted to outlines here, so the SVG renders the same without the font installed.
"""
import sys
from fontTools.ttLib import TTFont
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.varLib import instancer

frag, font_path, out = sys.argv[1:4]
mark = open(frag).read()
_fonts = {}


def text_path(text, wght, size, track):
    """Outline `text` at `size` px with tracking `track` (em); returns (path d, advance width, cap height)."""
    if wght not in _fonts:
        f = TTFont(font_path)
        if "fvar" in f:
            f = instancer.instantiateVariableFont(f, {"wght": wght})
        _fonts[wght] = f
    f = _fonts[wght]
    s = size / f["head"].unitsPerEm
    cmap, gs, hmtx = f.getBestCmap(), f.getGlyphSet(), f["hmtx"]
    x, d = 0.0, []
    names = [cmap[ord(c)] for c in text]
    for i, n in enumerate(names):
        pen = SVGPathPen(gs)
        gs[n].draw(TransformPen(pen, (s, 0, 0, -s, x, 0)))
        d.append(pen.getCommands())
        x += hmtx[n][0] * s + (track * size if i < len(names) - 1 else 0)
    return " ".join(d), x, f["OS/2"].sCapHeight * s


W, H = 1600, 440
SIZE, TRACK, WORD_GAP = 118, -0.035, 25
d1, w1, cap = text_path("Croky", 700, SIZE, TRACK)
d2, w2, _ = text_path("Chords", 700, SIZE, TRACK)
d3, _, _ = text_path("chord progression editor", 500, 27, 0.01)
wm_w = w1 + WORD_GAP + w2

# The mark is 64 art units; the bird spans x 0.3..63.6 and y 3..58 of that box.
MS = 4.9
mark_w, mark_h = 63.4 * MS, 55 * MS
GAP = 58
x0 = round((W - (mark_w + GAP + wm_w)) / 2)
my = (H - mark_h) / 2 - 3 * MS - 6          # bird optically centred (its weight sits low)
tx = x0 + mark_w + GAP
base = round(H / 2 + cap / 2) - 18          # caps centred on the head-to-belly middle

svg = f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {W} {H}" width="{W}" height="{H}" role="img" aria-label="Croky Chords">
  <!-- Concept A: flat vector Croky + one-colour grotesk wordmark (Schibsted Grotesk Bold, outlined).
       Generated by tools/brand/concept_a.py; see docs/BRAND.md, "Banner concepts". -->
  <rect width="{W}" height="{H}" fill="#121212"/>
  <g transform="translate({x0 - 0.3 * MS:.1f} {my:.1f}) scale({MS})">
{mark}  </g>
  <g fill="#f2e5bc" transform="translate({tx:.1f} {base})">
    <path d="{d1}"/>
    <path transform="translate({w1 + WORD_GAP:.1f} 0)" d="{d2}"/>
  </g>
  <path fill="#7d786c" transform="translate({tx + 4:.1f} {base + 62})" d="{d3}"/>
</svg>
'''
open(out, "w").write(svg)
