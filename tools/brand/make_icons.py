"""make_icons.py MASTER_DIR OUT_DIR  -- favicon, touch icon and toolbar logomark from the pixel master.

Same pixels as the README banner (concept_b.py), drawn by the maintainer at each size: croky-32.txt for
the SVG favicon, the 32 px PNG, the touch icon and the logomark, croky-16.txt for the 16 px PNG.
PNGs are written 1:1 or with an integer nearest-neighbour upscale; no anti-aliasing anywhere. Stdlib only."""
import os, sys

sys.dont_write_bytecode = True
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))  # `python3 -I` drops the script dir
from croky_pixels import load_grid, load_palette, colour_of, runs, hex_rgba, write_png

master, out = sys.argv[1:3]
pal = load_palette(os.path.join(master, "palette.json"))
col = colour_of(pal)
g32 = load_grid(os.path.join(master, "croky-32.txt"))
g16 = load_grid(os.path.join(master, "croky-16.txt"))
BG = "#121212"  # --bg-dark, same as the banner background
assert len(g32) == 32 and len(g32[0]) == 32 and len(g16) == 16 and len(g16[0]) == 16


def paths(rows, ox, oy):
    return "".join(f'<path fill="{c}" d="{"".join(d)}"/>' for c, d in runs(rows, ox, oy, col).items())


def save(name, text):
    open(os.path.join(out, name), "w").write(text)


def raster(rows, scale, size, bg=None):
    """rows drawn at an integer scale, centred on a size x size canvas (transparent or bg)."""
    n = len(rows) * scale
    off = (size - n) // 2
    fill = hex_rgba(bg) if bg else (0, 0, 0, 0)
    px = [[fill] * size for _ in range(size)]
    for y in range(n):
        for x in range(n):
            c = col(rows[y // scale][x // scale])
            if c:
                px[off + y][off + x] = hex_rgba(c)
    return px


# Favicon: the whole bird, transparent, one cell per pixel at 32 px.
save("favicon.svg", f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 32 32" width="32" height="32" shape-rendering="crispEdges">
  <!-- Pixel Croky (croky-32 master). Generated by tools/brand/make_icons.py; see docs/BRAND.md. -->
  {paths(g32, 0, 0)}
</svg>
''')

# Logomark: the same bird on the dark disc, 4-cell margin, 8 px per cell (320 x 320).
S, PAD = 8, 4
N = 32 + 2 * PAD
save("croky-mark.svg", f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {N * S} {N * S}" width="{N * S}" height="{N * S}" role="img" aria-label="Croky Chords" shape-rendering="crispEdges">
  <!-- Pixel Croky (croky-32 master) on the dark disc. Generated by tools/brand/make_icons.py; see docs/BRAND.md. -->
  <circle cx="{N * S // 2}" cy="{N * S // 2}" r="{N * S // 2}" fill="{BG}"/>
  <g transform="scale({S})">{paths(g32, PAD, PAD)}</g>
</svg>
''')

write_png(os.path.join(out, "favicon-32.png"), 32, 32, raster(g32, 1, 32))
write_png(os.path.join(out, "favicon-16.png"), 16, 16, raster(g16, 1, 16))
# Touch icon: opaque (iOS fills transparency with black anyway), 32 cells x 5 = 160 px on 180.
write_png(os.path.join(out, "apple-touch-icon.png"), 180, 180, raster(g32, 5, 180, BG))
print("wrote favicon.svg, croky-mark.svg, favicon-32.png, favicon-16.png, apple-touch-icon.png to", out)
