"""Rasterise the Pixel theme's font for the Fire OLED into apps/web/src/midi/fire/font.ts.

The Pixel theme uses Departure Mono (SIL OFL 1.1, apps/web/public/fonts/DepartureMono-OFL.txt), a
pixel font drawn on an 11 px grid: at 11 px every glyph lands on whole pixels in a 7 x 11 cell.
This script renders each glyph once at that size and writes the 1-bit rows as a TypeScript table, so
the web app needs no font loading or canvas to draw text on the OLED.

    uv run --no-project --with pillow --with fonttools --with brotli python -I tools/fire/oled_font.py
"""

from __future__ import annotations

import os

from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
FONT = os.path.join(ROOT, "apps/web/public/fonts/DepartureMono-Regular.woff2")
OUT = os.path.join(ROOT, "apps/web/src/midi/fire/font.ts")
SIZE = 11
WIDTH = 7  # advance of every glyph at 11 px
TOP = 2  # first row any glyph uses
HEIGHT = 11  # rows 2..12: brackets reach row 2, descenders row 12
CHARS = [chr(c) for c in range(0x20, 0x7F)] + ["°", "ø"]


def glyph_rows(font: ImageFont.FreeTypeFont, ch: str) -> list[int]:
    img = Image.new("L", (WIDTH + 4, TOP + HEIGHT + 4), 0)
    ImageDraw.Draw(img).text((0, 0), ch, font=font, fill=255)
    rows = []
    for y in range(TOP, TOP + HEIGHT):
        mask = 0
        for x in range(WIDTH):
            if img.getpixel((x, y)) > 127:
                mask |= 1 << (WIDTH - 1 - x)
        rows.append(mask)
    return rows


def main() -> None:
    font = ImageFont.truetype(FONT, SIZE)
    lines = []
    for ch in CHARS:
        assert font.getlength(ch) == WIDTH, ch
        hexrows = "".join(f"{r:02x}" for r in glyph_rows(font, ch))
        key = "'\\\\'" if ch == "\\" else ("\"'\"" if ch == "'" else f"'{ch}'")
        lines.append(f"  [{key}, '{hexrows}'],")
    body = "\n".join(lines)
    ts = f"""/**
 * OLED glyphs of the Pixel theme's font, Departure Mono (SIL OFL 1.1, see
 * apps/web/public/fonts/DepartureMono-OFL.txt), rasterised at its native 11 px grid.
 * Generated by tools/fire/oled_font.py; do not edit by hand.
 *
 * Each glyph is {HEIGHT} rows of {WIDTH} pixels, two hex digits per row, bit 6 = leftmost pixel.
 * The cap height spans rows 1-8 of the cell, descenders rows 9-10.
 */

export const GLYPH_W = {WIDTH};
export const GLYPH_H = {HEIGHT};

export const GLYPHS: ReadonlyMap<string, string> = new Map([
{body}
]);
"""
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(ts)
    print(f"wrote {len(CHARS)} glyphs to {os.path.relpath(OUT, ROOT)}")


if __name__ == "__main__":
    main()
